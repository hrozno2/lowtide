#!/usr/bin/env node
/* Writes Casks/lowtide.rb for a published release.
 *
 * The cask lives in this repository rather than a separate homebrew-lowtide
 * one, which means the release workflow can commit it with the token GitHub
 * already gives every job, and nobody has to create a second repo or a
 * personal access token for a tap. Homebrew is happy to tap any repository
 * when it is given the URL:
 *
 *   brew tap hrozno2/lowtide https://github.com/hrozno2/lowtide
 *   brew install --cask lowtide
 *
 * Run by hand as:  node scripts/update-homebrew-tap.mjs 1.0.28
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const version = process.argv[2];
if (!version) {
  console.error('usage: node scripts/update-homebrew-tap.mjs <version>');
  process.exit(1);
}

const REPO = 'hrozno2/lowtide';
const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, '..', 'Casks', 'lowtide.rb');

const urlFor = (arch) =>
  `https://github.com/${REPO}/releases/download/v${version}/LowTide-${version}-mac-${arch}.dmg`;

/** The hash Homebrew checks the download against, taken from the download. */
async function sha256Of(url) {
  const res = await fetch(url, { redirect: 'follow' });
  if (!res.ok) throw new Error(`could not fetch ${url}: ${res.status} ${res.statusText}`);
  return createHash('sha256').update(Buffer.from(await res.arrayBuffer())).digest('hex');
}

const [arm, intel] = await Promise.all([sha256Of(urlFor('arm64')), sha256Of(urlFor('x64'))]);

const cask = `# Generated by scripts/update-homebrew-tap.mjs on each release.
cask "lowtide" do
  arch arm: "arm64", intel: "x64"

  version "${version}"
  sha256 arm:   "${arm}",
         intel: "${intel}"

  url "https://github.com/${REPO}/releases/download/v#{version}/LowTide-#{version}-mac-#{arch}.dmg",
      verified: "github.com/${REPO}/"
  name "Low Tide"
  desc "Writing app for novels and screenplays"
  homepage "https://github.com/${REPO}"

  app "Low Tide.app"

  zap trash: [
    "~/Library/Application Support/Low Tide",
    "~/Library/Preferences/com.lowtide.writer.plist",
    "~/Library/Saved Application State/com.lowtide.writer.savedState",
  ]
end
`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, cask, 'utf8');
console.log(`Casks/lowtide.rb now points at ${version}`);
console.log(`  arm64 ${arm}`);
console.log(`  x64   ${intel}`);
